#!/bin/sh
# Regenerates floatfmt_blob.go from floatfmt.c (developer tool only; the
# generated blob is committed, so building Mio does not need gcc/objcopy).
set -eu
cd "$(dirname "$0")"
tmp=$(mktemp -d)
gcc -O2 -ffreestanding -fno-builtin -nostdlib -fPIC -fno-pic -mno-red-zone -fno-stack-protector \
  -fno-tree-loop-distribute-patterns -fno-reorder-blocks-and-partition -fno-reorder-functions -fno-jump-tables -fno-tree-vectorize -fno-tree-slp-vectorize -fcf-protection=none -fno-asynchronous-unwind-tables -fno-unwind-tables \
  -c floatfmt.c -o "$tmp/f.o"
if objdump -dr "$tmp/f.o" | grep -E "R_X86_64|call.*(mem|__)"; then echo "relocation/libc call found" >&2; exit 1; fi
nm "$tmp/f.o" | grep -q "^0000000000000000 T mio_fmt_float" || { echo "entry not at offset 0" >&2; exit 1; }
objcopy -O binary -j .text "$tmp/f.o" "$tmp/f.bin"
python3 - "$tmp/f.bin" ../floatfmt_blob.go floatfmt.c <<'PY'
import sys, hashlib
b=open(sys.argv[1],'rb').read()
# SHA-256 of the C source with CRLF normalised to LF, so a checkout with CRLF line endings matches.
digest=hashlib.sha256(open(sys.argv[3],'rb').read().replace(b'\r\n',b'\n')).hexdigest()
rows=[', '.join('0x%02x'%x for x in b[i:i+12]) for i in range(0,len(b),12)]
open(sys.argv[2],'w').write('// Code generated by runtime/gen.sh from runtime/floatfmt.c; DO NOT EDIT.\n\npackage linuxamd64\n\n// floatFmtSourceSHA256 is the SHA-256 of runtime/floatfmt.c (CRLF normalised to LF) this blob was built from.\nconst floatFmtSourceSHA256 = "'+digest+'"\n\n// floatFmtBlob is position-independent code for mio_fmt_float (entry at offset 0 of the blob).\nvar floatFmtBlob = []byte{\n\t'+',\n\t'.join(rows)+',\n}\n')
PY
rm -rf "$tmp"
