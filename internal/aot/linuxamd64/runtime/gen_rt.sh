#!/bin/sh
# Regenerates ../rt_blob.go from rt.c (developer tool; the blob is committed).
set -eu
cd "$(dirname "$0")"
tmp=$(mktemp -d)
gcc -O2 -ffreestanding -fno-builtin -nostdlib -fno-pic -mno-red-zone -fno-stack-protector \
  -fno-tree-loop-distribute-patterns -fno-reorder-blocks-and-partition -fno-reorder-functions -fno-jump-tables \
  -fno-tree-vectorize -fno-tree-slp-vectorize -fcf-protection=none -fno-asynchronous-unwind-tables -fno-unwind-tables \
  -mcmodel=small -c rt.c -o "$tmp/r.o"
if objdump -dr "$tmp/r.o" | grep -E "R_X86_64|call.*(mem|__)"; then echo "relocation/libc call found" >&2; exit 1; fi
if objdump -h "$tmp/r.o" | awk '/\.(rodata|data|bss)/ && $3 != "00000000" {bad=1} END {exit !bad}'; then echo "non-empty data section" >&2; exit 1; fi
entry=$(nm "$tmp/r.o" | awk '$3=="mio_rt"{print $1}' | python3 -c 'import sys;print(int(sys.stdin.read().strip(),16))')
objcopy -O binary -j .text "$tmp/r.o" "$tmp/r.bin"
python3 - "$tmp/r.bin" ../rt_blob.go "$entry" rt.c <<'PY'
import sys, hashlib
b=open(sys.argv[1],'rb').read()
# SHA-256 of the C source with CRLF normalised to LF, so a checkout with CRLF line endings matches.
digest=hashlib.sha256(open(sys.argv[4],'rb').read().replace(b'\r\n',b'\n')).hexdigest()
rows=[', '.join('0x%02x'%x for x in b[i:i+12]) for i in range(0,len(b),12)]
open(sys.argv[2],'w').write('// Code generated by runtime/gen_rt.sh from runtime/rt.c; DO NOT EDIT.\n\npackage linuxamd64\n\n// rtBlob is position-independent code; mio_rt is at rtEntry.\nconst rtEntry = '+sys.argv[3]+'\n\n// rtSourceSHA256 is the SHA-256 of runtime/rt.c (CRLF normalised to LF) this blob was built from.\nconst rtSourceSHA256 = "'+digest+'"\n\nvar rtBlob = []byte{\n\t'+',\n\t'.join(rows)+',\n}\n')
PY
rm -rf "$tmp"
