#!/usr/bin/env python3
"""Isolated verification of Mio's native Mach-O signer; no target is externally signed."""
import argparse,hashlib,json,os,shutil,signal,subprocess,time
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--compiler',type=Path,required=True);p.add_argument('--corpus',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[1];out=a.output.resolve();out.mkdir(parents=True,exist_ok=False);compiler=a.compiler.resolve();commands=[]
def run(label,argv,stdin=None,timeout=180):
 with (out/(label+'.stdout')).open('wb') as stdout,(out/(label+'.stderr')).open('wb') as stderr:
  start=time.monotonic();proc=subprocess.Popen(['/usr/bin/time','-l',*map(str,argv)],cwd=out,env={'PATH':''},stdin=subprocess.PIPE,stdout=stdout,stderr=stderr,start_new_session=True)
  try:proc.communicate(stdin,timeout=timeout);code=proc.returncode
  except subprocess.TimeoutExpired:os.killpg(proc.pid,signal.SIGKILL);proc.communicate();code=None
 commands.append({'label':label,'argv':list(map(str,argv)),'cwd':str(out),'environment':{'PATH':''},'exit_code':code,'wall_seconds':time.monotonic()-start});(out/'commands.json').write_text(json.dumps(commands,indent=2)+'\n');return code
src=out/'case.mio';src.write_text('''yobu "kiso/aot/sign"; yobu "kiso/fs"; yobu "kiso/math"; yobu "kiso/string";
kaku input = fs.read_all("input.bin"); moshi (input.error != mu) { math.fail("input"); }
kaku signed = sign.adhoc(input.data); moshi (signed.error != "") { fs.write_all("/dev/stderr", string.to_bytes(signed.error)); math.fail("sign"); }
kaku result = fs.write_all("signed.bin", signed.bytes); moshi (result.error != mu) { math.fail("output"); }
''')
def policy(label,exe):
 p=out/(label+'.sb');p.write_text('(version 1)(allow default)(deny process-fork)(deny process-exec)(allow process-exec (literal '+json.dumps(str(exe))+'))\n');return ['/usr/bin/sandbox-exec','-f',p,exe]
unsigned=out/'image.unsigned';request=('\n'.join(map(str,[root,src,root/'bunko',unsigned]))+'\n').encode();(out/'compile.stdin').write_bytes(request)
assert run('compile',policy('compiler',compiler),request)==0
signer=out/'signer.native';shutil.copy2(unsigned,signer);signer.chmod(0o755)
# One-time development seed preparation only. Tested output bytes below are
# generated by this native Mio signer and never passed to codesign --sign.
assert run('signer-seed-sign',['/usr/bin/codesign','--force','--sign','-',signer])==0
assert run('signer-seed-verify',['/usr/bin/codesign','--verify','--strict',signer])==0
results=[]
for name in ['0-normal','5-stress','9-normal','array-scalar-storage-stress','native-fs-map-offset']:
 directory=a.corpus.resolve()/name
 image=directory/'application.unsigned'
 if not image.exists():image=directory/'image.unsigned'
 assert image.exists(),image
 (out/'input.bin').write_bytes(image.read_bytes());target=out/'signed.bin';target.unlink(missing_ok=True)
 code=run(name+'-sign',policy('signer',signer))
 if code==0 and target.exists():
  kept=out/(name+'.native');shutil.copy2(target,kept);kept.chmod(0o755)
  verify=run(name+'-verify',['/usr/bin/codesign','--verify','--strict',kept]);execution=run(name+'-execute',[kept]);actual=(out/(name+'-execute.stdout')).read_bytes()
  expected=(a.corpus.resolve()/(name+'-native.stdout')).read_bytes()
  results.append({'case':name,'sign_exit':code,'verify_exit':verify,'run_exit':execution,'sha256':hashlib.sha256(kept.read_bytes()).hexdigest(),'status':'PASS' if verify==execution==0 and actual==expected else 'FAIL'})
  if name=='0-normal':
   altered=bytearray(kept.read_bytes());altered[768]^=1;bad=out/'tampered.native';bad.write_bytes(altered);bad.chmod(0o755);rejected=run('tamper-verify',['/usr/bin/codesign','--verify','--strict',bad]);results.append({'case':'tampered-page-rejected','exit':rejected,'status':'PASS' if rejected not in (None,0) else 'FAIL'})
 else:results.append({'case':name,'sign_exit':code,'status':'FAIL_SIGN'})
 (out/'results.json').write_text(json.dumps(results,indent=2)+'\n');print(name,results[-1]['status'],flush=True)
manifest=[{'path':str(x.relative_to(root)),'sha256':hashlib.sha256(x.read_bytes()).hexdigest()} for x in sorted(set(root.glob('bunko/**/*.mio'))|set(root.glob('selfhost/**/*.mio')))];(out/'source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
raise SystemExit(0 if all(x['status']=='PASS' for x in results) else 1)
